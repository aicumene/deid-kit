"""Dev only: Python's own text rules as Rust tables (src/unicode_tables.rs), so the Rust deid-kit folds,
splits, cases and normalises text exactly as the Python one does — the vault's keys depend on it.
Run with the Python the desktop's runtime carries (3.13, Unicode 15.1):

    python tools/gen_unicode.py > src/unicode_tables.rs

Per code point: the general category, the combining class, the one-level decomposition (canonical or
compatibility), the primary composites (a pair that NFC composes back), lower/upper/title/casefold
where they change it, and the sets str.isspace, str.isdigit, str.isnumeric, str.islower, str.isupper and
re's \\w answer yes for.
"""

import re
import sys
import unicodedata

CATS = ["Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi",
        "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"]

ALL = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def runs(value_of):
    """(start, end, value) for every run of code points with the same value (surrogates as Cs/0)."""
    out = []
    for cp in range(0x110000):
        v = value_of(cp)
        if out and out[-1][2] == v and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp, v])
    return out


def rs_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def main() -> None:
    w = sys.stdout.write
    w(f"// Generated by tools/gen_unicode.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n")
    w("// Do not edit: run the script again.\n#![allow(clippy::all)]\n")
    w(f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";\n')
    w("pub static CATEGORY_NAMES: [&str; %d] = [%s];\n" % (len(CATS), ", ".join(f'"{c}"' for c in CATS)))

    def cat(cp):
        return CATS.index("Cs" if 0xD800 <= cp <= 0xDFFF else unicodedata.category(chr(cp)))

    cr = runs(cat)
    w(f"/// (first, last, index into CATEGORY_NAMES).\npub static CATEGORY: [(u32, u32, u8); {len(cr)}] = [")
    w(", ".join(f"(0x{a:x}, 0x{b:x}, {v})" for a, b, v in cr) + "];\n")

    ccc = [r for r in runs(lambda cp: 0 if 0xD800 <= cp <= 0xDFFF else unicodedata.combining(chr(cp))) if r[2]]
    w(f"/// (first, last, canonical combining class), where it is not 0.\npub static CCC: [(u32, u32, u8); {len(ccc)}] = [")
    w(", ".join(f"(0x{a:x}, 0x{b:x}, {v})" for a, b, v in ccc) + "];\n")

    decomp, compose = [], []
    for cp in ALL:
        d = unicodedata.decomposition(chr(cp))
        if not d:
            continue
        compat = d.startswith("<")
        parts = [int(x, 16) for x in d.split() if not x.startswith("<")]
        decomp.append((cp, compat, parts))
        if not compat and len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    w(f"/// (code point, compatibility, one level of decomposition).\npub static DECOMPOSITION: [(u32, bool, &[u32]); {len(decomp)}] = [")
    w(", ".join(f"(0x{cp:x}, {str(c).lower()}, &[{', '.join(f'0x{p:x}' for p in ps)}])" for cp, c, ps in decomp) + "];\n")
    compose.sort()
    w(f"/// (first, second, composite): the pairs NFC composes.\npub static COMPOSITION: [(u32, u32, u32); {len(compose)}] = [")
    w(", ".join(f"(0x{a:x}, 0x{b:x}, 0x{c:x})" for a, b, c in compose) + "];\n")

    for name, f in (("LOWER", str.lower), ("UPPER", str.upper), ("TITLE", str.title), ("CASEFOLD", str.casefold)):
        rows = [(cp, f(chr(cp))) for cp in ALL if f(chr(cp)) != chr(cp)]
        w(f"pub static {name}: [(u32, &str); {len(rows)}] = [" + ", ".join(f"(0x{cp:x}, {rs_str(s)})" for cp, s in rows) + "];\n")

    sets = {
        "SPACE": lambda ch: ch.isspace(),
        "DIGIT": lambda ch: ch.isdigit(),
        "NUMERIC": lambda ch: ch.isnumeric(),
        "LOWERCASE": lambda ch: ch.islower(),
        "UPPERCASE": lambda ch: ch.isupper(),
        "WORD": lambda ch: re.match(r"\w", ch) is not None,
        "PRINTABLE": lambda ch: ch.isprintable(),
    }
    for name, test in sets.items():
        rs = ranges([cp for cp in ALL if test(chr(cp))])
        w(f"pub static {name}: [(u32, u32); {len(rs)}] = [" + ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in rs) + "];\n")
    zeros = [cp for cp in ALL if unicodedata.decimal(chr(cp), -1) == 0]
    assert all(unicodedata.decimal(chr(z + i), -1) == i for z in zeros for i in range(10))
    w(f"/// The zero of every run of ten decimal digits.\npub static DIGIT_ZEROS: [u32; {len(zeros)}] = [" +
      ", ".join(f"0x{z:x}" for z in zeros) + "];\n")


if __name__ == "__main__":
    main()


def sre_tables() -> None:
    """What re's IGNORECASE compares: the simple lower case (_sre.unicode_tolower) and the extra
    equivalences (re._casefix._EXTRA_CASES: ſ with s, K with k, ...)."""
    import _sre
    from re import _casefix
    w = sys.stdout.write
    low = [(cp, _sre.unicode_tolower(cp)) for cp in ALL if _sre.unicode_tolower(cp) != cp]
    w(f"pub static SIMPLE_LOWER: [(u32, u32); {len(low)}] = [" + ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in low) + "];\n")
    cased = ranges([cp for cp in ALL if _sre.unicode_iscased(cp)])
    w(f"pub static SRE_CASED: [(u32, u32); {len(cased)}] = [" + ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in cased) + "];\n")
    extra = sorted(_casefix._EXTRA_CASES.items())
    w(f"pub static EXTRA_CASES: [(u32, &[u32]); {len(extra)}] = [" +
      ", ".join(f"(0x{k:x}, &[{', '.join(f'0x{x:x}' for x in v)}])" for k, v in extra) + "];\n")


if __name__ == "__main__":
    sre_tables()
