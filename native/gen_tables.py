"""The tables deidkit_fold works from, made by the interpreter the module is built for (build.rs runs this
with it): per code point, what deidkit.namefold asks of that interpreter's Unicode database — NFKC,
casefold, the categories, ``\\s``, and the single base character NFD leaves. The tables carry the Unicode
version they came from; deidkit.namefold uses the module only when its interpreter has the same one, so
the Rust fold and the Python fold answer from the same data.

    python gen_tables.py OUT.rs
"""

import re
import sys
import unicodedata

_WS_RE = re.compile(r"\s")              # deidkit.namefold._WS_RE
_MARK_CATS = ("Mn", "Mc", "Me")         # deidkit.namefold._MARK_CATS


def nfd_base(ch: str) -> str | None:
    """deidkit.namefold.confusable: the base NFD leaves once its combining marks are gone, if one."""
    base = "".join(c for c in unicodedata.normalize("NFD", ch) if unicodedata.combining(c) == 0)
    return base if len(base) == 1 else None


def rs_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def main(out_path: str) -> None:
    nfkc, casefold, base = [], [], []
    sets = {"CF": [], "SPACE": [], "CLUSTER_MARK": [], "MARK": []}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        n = unicodedata.normalize("NFKC", ch)
        if n != ch:
            nfkc.append((cp, n))
        f = ch.casefold()
        if f != ch:
            casefold.append((cp, f))
        b = nfd_base(ch)
        if b is not None and b != ch:
            base.append((cp, b))
        cat = unicodedata.category(ch)
        if cat == "Cf":
            sets["CF"].append(cp)
        if _WS_RE.match(ch):
            sets["SPACE"].append(cp)
        if unicodedata.combining(ch) != 0 or cat in _MARK_CATS:
            sets["CLUSTER_MARK"].append(cp)
        if cat in _MARK_CATS:
            sets["MARK"].append(cp)

    def ranges(cps: list[int]) -> list[tuple[int, int]]:
        out: list[tuple[int, int]] = []
        for cp in cps:
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
        return out

    lines = [
        "// Generated by gen_tables.py from this interpreter's Unicode database — do not edit.",
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";',
        f'pub const PYTHON_VERSION: &str = "{sys.version.split()[0]}";',
        "pub static NFKC: &[(u32, &str)] = &[" + ",".join(f"(0x{cp:x},{rs_str(s)})" for cp, s in nfkc) + "];",
        "pub static CASEFOLD: &[(u32, &str)] = &[" + ",".join(f"(0x{cp:x},{rs_str(s)})" for cp, s in casefold) + "];",
        "pub static NFD_BASE: &[(u32, char)] = &[" + ",".join(f"(0x{cp:x},'\\u{{{ord(b):x}}}')" for cp, b in base) + "];",
    ]
    for name, cps in sets.items():
        lines.append(f"pub static {name}: &[(u32, u32)] = &[" +
                     ",".join(f"(0x{a:x},0x{b:x})" for a, b in ranges(cps)) + "];")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
